#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate a deterministic occupancy map (PGM + YAML) for Nav2 map_server / amcl
that matches EXACTLY the scene rendered by synthetic_scan_publisher.py, so a
Nav2 baseline can be measured against the same synthetic 5 Hz LiDAR stimulus
without Gazebo or a rosbag.

Scene (must stay byte-identical with synthetic_scan_publisher.py):
  ROOM_HALF = 5.0   -> 10 m x 10 m square room
  PILLARS    = [(2.0, 1.0, 0.5, 0.5), (-2.0, -2.0, 0.8, 0.4)]
  resolution = 0.05 m -> 200 x 200 grid

Occupancy semantics for map_server nav_msgs/OccupancyGrid conversion:
  - free  = 0,   occupied = 100, unknown = -1 (outside the room)
The YAML 'origin' is the map bottom-left corner in map frame.

Usage:
  python3 gen_synthetic_map.py --out /oomwoo/.../results/nav2_map
  writes nav2_map.pgm + nav2_map.yaml
"""

import argparse

ROOM_HALF = 5.0
PILLARS = [
    (2.0, 1.0, 0.5, 0.5),
    (-2.0, -2.0, 0.8, 0.4),
]
RES = 0.05          # metres per pixel
N = int(2 * ROOM_HALF / RES)   # 200


def cell_occupied(wx, wy):
    """True if world point is on a wall or inside a pillar (absorbs scan)."""
    h = ROOM_HALF
    if abs(wx) >= h or abs(wy) >= h:
        return True                          # wall line
    for (cx, cy, hx, hy) in PILLARS:
        if abs(wx - cx) <= hx and abs(wy - cy) <= hy:
            return True
    return False


def make_grid():
    """grid[y][x]; y index = row measured from map bottom (world +Y up)."""
    grid = []
    for i in range(N):
        wy = -ROOM_HALF + (i + 0.5) * RES
        row = []
        for j in range(N):
            wx = -ROOM_HALF + (j + 0.5) * RES
            row.append(cell_occupied(wx, wy))
        grid.append(row)
    return grid


def write_pgm(path, grid):
    """PGM P5 binary; row 0 = top of image = max world Y."""
    with open(path, "wb") as f:
        f.write(b"P5\n%d %d\n255\n" % (N, N))
        for i in range(N - 1, -1, -1):       # top row first
            for j in range(N):
                f.write(b"\xff" if not grid[i][j] else b"\x00")


def write_yaml(path, pgm_name):
    yaml = """# Deterministic synthetic map for Nav2 benchmark (matches
# synthetic_scan_publisher.py scene). Generated by gen_synthetic_map.py.
image: %s
resolution: %.2f
origin: [%.2f, %.2f, 0.000]
negate: 0
occupied_thresh: 0.65
free_thresh: 0.196
""" % (pgm_name, RES, -ROOM_HALF, -ROOM_HALF)
    with open(path, "w") as f:
        f.write(yaml)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="synthetic_map",
                    help="output basename (writes .pgm and .yaml)")
    args = ap.parse_args()
    grid = make_grid()
    write_pgm(args.out + ".pgm", grid)
    write_yaml(args.out + ".yaml", args.out.split("/")[-1] + ".pgm")
    occ = sum(sum(r) for r in grid)
    print("wrote %s.pgm/.yaml (%dx%d, %d occupied cells @ %.2f m)" % (
        args.out, N, N, occ, RES))
